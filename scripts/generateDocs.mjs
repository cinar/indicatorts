// Generates the indicator and example strategy README.md files from the
// JSDoc comments in the source, so the documentation has a single source of
// truth. Run with --check to fail instead of writing when a README is stale.
//
// Conventions read from the source:
// - The category's index.ts starts with a JSDoc comment whose @module tag is
//   the README title and whose text is the README introduction.
// - Each module has one exported function tagged @title; its JSDoc becomes a
//   README section. Other exported functions in the module become
//   subsections. @example blocks, @param and @return tags are rendered too.
// - A function's <Name>Config interface and <Name>DefaultConfig constant,
//   its result interface, and `export { a as b }` aliases are documented
//   automatically.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'fs';
import { basename, dirname, join, relative } from 'path';
import { fileURLToPath } from 'url';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const CATEGORIES = [
  'src/indicator/momentum',
  'src/indicator/trend',
  'src/indicator/volatility',
  'src/indicator/volume',
  'examples/momentum',
  'examples/trend',
  'examples/volatility',
  'examples/volume',
];

const HEADER =
  '<!-- Generated by scripts/generateDocs.mjs from the JSDoc comments. DO NOT EDIT. -->';

const FOOTER = `## Disclaimer

The information provided on this project is strictly for informational purposes and is not to be construed as advice or solicitation to buy or sell any security.

## License

Copyright (c) 2022-2026 The Indicator Authors. All rights reserved.

The source code is provided under MIT License.
`;

/**
 * Parses a JSDoc comment into its description and tags.
 *
 * @param {string} comment raw comment text, including the delimiters.
 * @return {{description: string, tags: {name: string, text: string}[]}}
 */
export function parseJsDoc(comment) {
  const lines = comment
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split('\n')
    .map((line) => line.replace(/^\s*\* ?/, '').trimEnd());

  const description = [];
  const tags = [];
  let inFence = false;

  for (const line of lines) {
    const tag = !inFence && /^@(\w+)\s?(.*)$/.exec(line);
    if (tag) {
      tags.push({ name: tag[1], text: tag[2] });
    } else if (tags.length > 0) {
      const last = tags[tags.length - 1];
      last.text = last.text === '' ? line : `${last.text}\n${line}`;
    } else {
      description.push(line);
    }

    if (line.trimStart().startsWith('```')) {
      inFence = !inFence;
    }
  }

  return {
    description: description.join('\n').trim(),
    tags: tags.map((tag) => ({ ...tag, text: tag.text.trim() })),
  };
}

/**
 * Returns the GitHub anchor for a heading.
 *
 * @param {string} heading heading text.
 * @return {string}
 */
export function anchor(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

/** Returns the JSDoc comment attached to a node, or undefined. */
function jsDocOf(node, text) {
  const ranges = ts.getLeadingCommentRanges(text, node.pos) ?? [];
  const docs = ranges
    .map((range) => text.slice(range.pos, range.end))
    .filter((comment) => comment.startsWith('/**'));
  return docs.length > 0 ? parseJsDoc(docs[docs.length - 1]) : undefined;
}

/** Returns whether the node has an export modifier. */
const isExported = (node) =>
  ts
    .getModifiers(node)
    ?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) ??
  false;

/** Collects the documented declarations of one module file. */
function readModule(path) {
  const text = readFileSync(path, 'utf8');
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
  const module = {
    path,
    functions: [],
    interfaces: new Map(),
    defaults: new Map(),
    aliases: new Map(),
  };

  for (const statement of source.statements) {
    if (ts.isFunctionDeclaration(statement) && isExported(statement)) {
      module.functions.push({
        name: statement.name.text,
        doc: jsDocOf(statement, text) ?? { description: '', tags: [] },
        params: statement.parameters.map((param) => ({
          name: param.name.getText(source),
          type: param.type?.getText(source) ?? 'unknown',
          optional:
            param.initializer !== undefined || Boolean(param.questionToken),
        })),
        returnType: statement.type?.getText(source) ?? 'void',
      });
    } else if (ts.isInterfaceDeclaration(statement) && isExported(statement)) {
      module.interfaces.set(
        statement.name.text,
        statement.members.filter(ts.isPropertySignature).map((member) => ({
          name: member.name.getText(source),
          type: member.type?.getText(source) ?? 'unknown',
          description: jsDocOf(member, text)?.description ?? '',
        }))
      );
    } else if (ts.isVariableStatement(statement) && isExported(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (
          declaration.initializer &&
          ts.isObjectLiteralExpression(declaration.initializer)
        ) {
          module.defaults.set(
            declaration.name.getText(source),
            new Map(
              declaration.initializer.properties
                .filter(ts.isPropertyAssignment)
                .map((property) => [
                  property.name.getText(source),
                  property.initializer.getText(source),
                ])
            )
          );
        }
      }
    } else if (
      ts.isExportDeclaration(statement) &&
      !statement.moduleSpecifier &&
      statement.exportClause &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const element of statement.exportClause.elements) {
        const original = element.propertyName?.text ?? element.name.text;
        const aliases = module.aliases.get(original) ?? [];
        aliases.push(element.name.text);
        module.aliases.set(original, aliases);
      }
    }
  }

  return module;
}

/** Wraps the text in Markdown inline code. */
const code = (text) => `\`${text}\``;

/** Renders a Markdown table, leaving out a last column that is all empty. */
function table(headers, rows) {
  const keep = rows.some((row) => row[row.length - 1] !== '')
    ? headers.length
    : headers.length - 1;
  /** Renders one table row with the kept columns. */
  const line = (cells) => `| ${cells.slice(0, keep).join(' | ')} |`;
  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)];
}
/** Escapes the text for use in a Markdown table cell. */
const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Renders the documentation of one function. */
function renderFunction(module, fn, heading) {
  const out = [heading, ''];
  /** Returns the function's JSDoc tags with the given name. */
  const tag = (name) => fn.doc.tags.filter((t) => t.name === name);

  if (fn.doc.description) {
    out.push(fn.doc.description, '');
  }

  const params = fn.params
    .map((p) => `${p.name}${p.optional ? '?' : ''}: ${p.type}`)
    .join(', ');
  out.push(
    '```TypeScript',
    `function ${fn.name}(${params}): ${fn.returnType}`,
    '```',
    ''
  );

  const paramDocs = new Map(
    tag('param').map((t) => {
      const [name, ...rest] = t.text.split(/\s+/);
      return [name, rest.join(' ')];
    })
  );
  if (fn.params.length > 0) {
    out.push(
      ...table(
        ['Parameter', 'Type', 'Description'],
        fn.params.map((p) => [
          code(p.name),
          code(cell(p.type)),
          cell(paramDocs.get(p.name) ?? ''),
        ])
      ),
      ''
    );
  }

  const returns = [...tag('return'), ...tag('returns')];
  if (returns.length > 0) {
    out.push(`**Returns:** ${returns[0].text}`, '');
  }

  for (const p of fn.params) {
    const members = module.interfaces.get(p.type);
    if (!members) {
      continue;
    }
    const defaults = module.defaults.get(
      p.type.replace(/Config$/, 'DefaultConfig')
    );
    out.push(
      `**${code(p.type)} options:**`,
      '',
      ...table(
        ['Option', 'Type', 'Default', 'Description'],
        members.map((member) => {
          const value = defaults?.get(member.name);
          return [
            code(member.name),
            code(cell(member.type)),
            value === undefined ? '' : code(cell(value)),
            cell(member.description),
          ];
        })
      ),
      ''
    );
  }

  const result = module.interfaces.get(fn.returnType);
  if (result) {
    out.push(
      `**${code(fn.returnType)} fields:**`,
      '',
      ...table(
        ['Field', 'Type', 'Description'],
        result.map((member) => [
          code(member.name),
          code(cell(member.type)),
          cell(member.description),
        ])
      ),
      ''
    );
  }

  const aliases = module.aliases.get(fn.name);
  if (aliases) {
    out.push(`Also exported as ${aliases.map(code).join(', ')}.`, '');
  }

  const examples = tag('example');
  if (examples.length > 0) {
    out.push(examples.length > 1 ? '**Examples:**' : '**Example:**', '');
    for (const example of examples) {
      out.push(example.text, '');
    }
  }

  return out;
}

/** Renders the README of one category directory. */
export function renderCategory(category) {
  const dir = join(ROOT, category);
  const index = readFileSync(join(dir, 'index.ts'), 'utf8');
  const indexDoc = /\/\*\*[\s\S]*?\*\//.exec(index);
  if (!indexDoc) {
    throw new Error(`${category}/index.ts: missing module JSDoc comment`);
  }
  const moduleDoc = parseJsDoc(indexDoc[0]);
  const title = moduleDoc.tags.find((tag) => tag.name === 'module')?.text;
  if (!title) {
    throw new Error(`${category}/index.ts: missing @module tag`);
  }

  const sections = readdirSync(dir)
    .filter((name) => name.endsWith('.ts'))
    .filter((name) => name !== 'index.ts' && !name.endsWith('.test.ts'))
    .map((name) => {
      const module = readModule(join(dir, name));
      const titled = module.functions.filter((fn) =>
        fn.doc.tags.some((tag) => tag.name === 'title')
      );
      if (titled.length !== 1) {
        throw new Error(
          `${category}/${name}: expected exactly one exported function with @title, found ${titled.length}`
        );
      }
      const sectionTitle = titled[0].doc.tags.find(
        (tag) => tag.name === 'title'
      ).text;
      return { module, primary: titled[0], title: sectionTitle };
    })
    .sort((a, b) => a.title.localeCompare(b.title));

  const out = [HEADER, '', `# ${title}`, ''];
  if (moduleDoc.description) {
    out.push(moduleDoc.description, '');
  }

  out.push(`- [${title}](#${anchor(title)})`);
  for (const section of sections) {
    out.push(`  - [${section.title}](#${anchor(section.title)})`);
  }
  out.push('  - [Disclaimer](#disclaimer)', '  - [License](#license)', '');

  for (const { module, primary, title: sectionTitle } of sections) {
    out.push(...renderFunction(module, primary, `## ${sectionTitle}`));
    for (const fn of module.functions) {
      if (fn !== primary) {
        out.push(...renderFunction(module, fn, `### ${fn.name}`));
      }
    }
    const file = basename(module.path);
    out.push(`Source: [${file}](./${file})`, '');
  }

  out.push(FOOTER);
  return out.join('\n');
}

/**
 * Formats the README with the project's prettier configuration, so that
 * running prettier over the repository does not make the docs stale.
 */
async function formatReadme(path, content) {
  const options = (await resolveConfig(path)) ?? {};
  return format(content, { ...options, filepath: path });
}

/** Generates every README, or lists the stale ones when check is true. */
async function main(check) {
  const stale = [];

  for (const category of CATEGORIES) {
    const path = join(ROOT, category, 'README.md');
    const content = await formatReadme(path, renderCategory(category));
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';

    if (content !== current) {
      stale.push(relative(ROOT, path));
      if (!check) {
        writeFileSync(path, content);
      }
    }
  }

  if (check && stale.length > 0) {
    console.error(
      `Stale generated docs, run "npm run docs" and commit:\n  ${stale.join('\n  ')}`
    );
    process.exitCode = 1;
    return;
  }

  for (const path of stale) {
    console.log(`Updated ${path}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main(process.argv.includes('--check'));
}
